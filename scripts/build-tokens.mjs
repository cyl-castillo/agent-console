/* global process */
// DTCG tokens (tokens/*.tokens.json) → src/styles/tokens.css.
// Emits the primitive CSS variables for :root (dark) and
// :root[data-theme="light"]; derived values (color-mix, aliases) stay in
// global.css. Keep this tiny and deterministic: CI checks the output is
// committed (`npm run tokens && git diff --exit-code src/styles/tokens.css`).
import { readFileSync, writeFileSync } from "node:fs";

const [, , inPath = "tokens/console.tokens.json", outPath = "src/styles/tokens.css"] = process.argv;
const themePath = outPath.replace(/tokens\.css$/, "theme.css");
const doc = JSON.parse(readFileSync(inPath, "utf8"));

// CSS variable names are kept exactly as the app already uses them.
const names = {
  color: (n) => `--${n}`,
  font: (n) => `--font-${n}`,
  space: (n) => `--sp-${n}`,
  radius: (n) => `--r-${n}`,
  shadow: (n) => `--shadow-${n}`,
  motion: (n) => (n === "ease" ? "--ease" : `--${n}`),
};

const num = (v) => String(Math.round(v * 1000) / 1000);
const dim = (d) => `${num(d.value)}${d.unit}`;
const color = (c) => {
  if (c.alpha != null && c.alpha !== 1) {
    const [r, g, b] = c.components.map((x) => Math.round(x * 255));
    return `rgba(${r}, ${g}, ${b}, ${num(c.alpha)})`;
  }
  return c.hex ?? `rgb(${c.components.map((x) => Math.round(x * 255)).join(" ")})`;
};
const shadowLayer = (s) =>
  `${s.inset ? "inset " : ""}${dim(s.offsetX)} ${dim(s.offsetY)} ${dim(s.blur)}${
    s.spread && s.spread.value ? ` ${dim(s.spread)}` : ""
  } ${color(s.color)}`;
const serialize = (type, v) => {
  switch (type) {
    case "color":
      return color(v);
    case "dimension":
    case "duration":
      return dim(v);
    case "fontFamily":
      return v.map((f) => (/[^a-zA-Z0-9-]/.test(f) ? `"${f}"` : f)).join(", ");
    case "shadow":
      return (Array.isArray(v) ? v : [v]).map(shadowLayer).join(", ");
    case "cubicBezier":
      return `cubic-bezier(${v.map(num).join(", ")})`;
    default:
      throw new Error(`unsupported $type ${type}`);
  }
};

const dark = [];
const light = [];
for (const [group, toName] of Object.entries(names)) {
  for (const [name, token] of Object.entries(doc[group] ?? {})) {
    if (name.startsWith("$")) continue;
    const cssName = toName(name);
    const modes = token.$extensions?.mode;
    dark.push(`  ${cssName}: ${serialize(token.$type, modes?.dark ?? token.$value)};`);
    if (modes?.light) light.push(`  ${cssName}: ${serialize(token.$type, modes.light)};`);
  }
}

const out = `/* GENERATED by scripts/build-tokens.mjs from ${inPath} — do not edit.
   Primitive tokens only; derived values (color-mix steps, aliases, the
   elevation highlight) live next to their consumers in global.css. */

:root {
${dark.join("\n")}
}

:root[data-theme="light"] {
${light.join("\n")}
}
`;
writeFileSync(outPath, out);

// Tailwind 4 theme: every token becomes a utility namespace entry that
// resolves to the runtime variable (so dark/light switching keeps working),
// plus the semantic names the primitives in src/ui are written against.
const keys = (group) => Object.keys(doc[group] ?? {}).filter((n) => !n.startsWith("$"));
const themeLines = [
  ...keys("color").map((n) => `  --color-${n}: var(--${n});`),
  "  /* semantic aliases used by src/ui */",
  "  --color-background: var(--bg);",
  "  --color-foreground: var(--text);",
  "  --color-surface-1: var(--bg-elev-1);",
  "  --color-surface-2: var(--bg-elev-2);",
  "  --color-surface-3: var(--bg-elev-3);",
  "  --color-muted-foreground: var(--text-dim);",
  "  --color-faint-foreground: var(--text-faint);",
  "  --color-primary: var(--accent);",
  "  --color-destructive: var(--danger);",
  "  --color-success: var(--ok);",
  "  --color-warning: var(--warn);",
  "  --color-ring: var(--focus-color);",
  "  --font-mono: var(--font-mono);",
  "  --font-ui: var(--font-ui);",
  ...keys("space").map((n) => `  --spacing-${n}: var(--sp-${n});`),
  ...keys("radius").map((n) => `  --radius-${n}: var(--r-${n});`),
  ...keys("shadow").map((n) => `  --shadow-${n}: var(--shadow-${n});`),
  "  --ease-std: var(--ease);",
];
const theme = `/* GENERATED by scripts/build-tokens.mjs from ${inPath} — do not edit.
   Tailwind 4 theme namespace mapped onto the runtime tokens. */

@theme inline {
${themeLines.join("\n")}
}
`;
writeFileSync(themePath, theme);
console.log(
  `${outPath}: ${dark.length} dark, ${light.length} light · ${themePath}: ${themeLines.length} entries`,
);
