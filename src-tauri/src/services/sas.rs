/// Four words from the first four bytes of the handshake hash.
pub fn sas_from_hash(hash: &[u8]) -> String {
    hash.iter()
        .take(4)
        .map(|b| WORDS[*b as usize])
        .collect::<Vec<_>>()
        .join("-")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Known answer shared with the companion's test: the same bytes must
    /// give the same words on both sides.
    #[test]
    fn the_words_are_a_fixed_function_of_the_hash() {
        assert_eq!(
            sas_from_hash(&[0, 1, 2, 3, 99, 100]),
            "acorn-amber-anchor-apple"
        );
        assert_eq!(
            sas_from_hash(&[255, 254, 253, 252]),
            "zinc-zephyr-zebra-yarn"
        );
        assert_eq!(sas_from_hash(&[7, 7, 7, 7]), "badge-badge-badge-badge");
        let unique: std::collections::HashSet<&str> = WORDS.iter().copied().collect();
        assert_eq!(unique.len(), 256);
        assert!(WORDS
            .iter()
            .all(|w| w.len() >= 3 && w.chars().all(|c| c.is_ascii_lowercase())));
    }
}
